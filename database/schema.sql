CREATE DATABASE IF NOT EXISTS vetesta CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE vetesta;

CREATE TABLE clinics (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(160) NOT NULL UNIQUE,
 email VARCHAR(190) NOT NULL, active TINYINT(1) NOT NULL DEFAULT 1,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE admins (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE vet_users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, clinic_id BIGINT UNSIGNED NOT NULL,
 username VARCHAR(100) NOT NULL, email VARCHAR(190) NOT NULL, password_hash VARCHAR(255) NOT NULL,
 active TINYINT(1) NOT NULL DEFAULT 1, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uq_vet_email (clinic_id,email), CONSTRAINT fk_vu_clinic FOREIGN KEY(clinic_id) REFERENCES clinics(id)
);
CREATE TABLE clients (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, dni VARCHAR(30) NOT NULL UNIQUE,
 full_name VARCHAR(180) NOT NULL, email VARCHAR(190) NOT NULL, phone VARCHAR(50) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
);
CREATE TABLE clinic_clients (
 clinic_id BIGINT UNSIGNED NOT NULL, client_id BIGINT UNSIGNED NOT NULL,
 first_seen_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP, last_seen_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY(clinic_id,client_id),
 FOREIGN KEY(clinic_id) REFERENCES clinics(id), FOREIGN KEY(client_id) REFERENCES clients(id)
);
CREATE TABLE pets (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, client_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(120) NOT NULL, animal_type VARCHAR(80) NOT NULL, breed VARCHAR(120) NULL,
 weight_kg DECIMAL(7,2) NULL, height_cm DECIMAL(7,2) NULL, birth_date DATE NULL,
 photo_path VARCHAR(255) NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(client_id) REFERENCES clients(id)
);
CREATE TABLE consultations (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, pet_id BIGINT UNSIGNED NOT NULL,
 clinic_id BIGINT UNSIGNED NOT NULL, vet_user_id BIGINT UNSIGNED NOT NULL,
 reason VARCHAR(100) NOT NULL, notes TEXT NOT NULL, diagnosis TEXT NULL, treatment TEXT NULL,
 status ENUM('En proceso','Dado de Alta') NOT NULL DEFAULT 'En proceso',
 vaccine_expiry DATE NULL, next_dose DATE NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(pet_id) REFERENCES pets(id), FOREIGN KEY(clinic_id) REFERENCES clinics(id),
 FOREIGN KEY(vet_user_id) REFERENCES vet_users(id), INDEX(pet_id,created_at)
);
CREATE TABLE medications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, clinic_id BIGINT UNSIGNED NOT NULL,
 name VARCHAR(180) NOT NULL, quantity INT NOT NULL DEFAULT 0, updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(clinic_id) REFERENCES clinics(id), UNIQUE KEY uq_med_name(clinic_id,name)
);
CREATE TABLE consultation_medications (
 consultation_id BIGINT UNSIGNED NOT NULL, medication_id BIGINT UNSIGNED NULL,
 other_medication VARCHAR(180) NULL, purchase_needed TINYINT(1) NOT NULL DEFAULT 0,
 PRIMARY KEY(consultation_id), FOREIGN KEY(consultation_id) REFERENCES consultations(id),
 FOREIGN KEY(medication_id) REFERENCES medications(id)
);
CREATE TABLE appointments (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, clinic_id BIGINT UNSIGNED NOT NULL,
 client_id BIGINT UNSIGNED NOT NULL, pet_id BIGINT UNSIGNED NOT NULL, requested_by ENUM('cliente','veterinaria') NOT NULL,
 appointment_at DATETIME NOT NULL, reason VARCHAR(255) NULL,
 status ENUM('Solicitado','Confirmado','Cancelado','Atendido') NOT NULL DEFAULT 'Solicitado',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(clinic_id) REFERENCES clinics(id), FOREIGN KEY(client_id) REFERENCES clients(id),
 FOREIGN KEY(pet_id) REFERENCES pets(id), INDEX(clinic_id,appointment_at)
);
CREATE TABLE consultation_files (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, consultation_id BIGINT UNSIGNED NOT NULL,
 uploaded_by ENUM('cliente','veterinaria') NOT NULL, uploader_id BIGINT UNSIGNED NOT NULL,
 original_name VARCHAR(255) NOT NULL, stored_name VARCHAR(255) NOT NULL, mime_type VARCHAR(120) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(consultation_id) REFERENCES consultations(id)
);
CREATE TABLE audit_log (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, clinic_id BIGINT UNSIGNED NULL,
 vet_user_id BIGINT UNSIGNED NULL, entity_type VARCHAR(60) NOT NULL, entity_id BIGINT UNSIGNED NOT NULL,
 action VARCHAR(60) NOT NULL, details JSON NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(clinic_id) REFERENCES clinics(id), FOREIGN KEY(vet_user_id) REFERENCES vet_users(id)
);

CREATE TABLE remember_tokens (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 vet_user_id BIGINT UNSIGNED NOT NULL,
 selector CHAR(24) NOT NULL UNIQUE,
 validator_hash CHAR(64) NOT NULL,
 expires_at DATETIME NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(vet_user_id) REFERENCES vet_users(id) ON DELETE CASCADE
);
